STATE_HOME = None


def isolate_state():
    """Point the tool's per-user state (case files, labels, merge decisions, alert rules) at an empty temporary
    folder, so nothing saved on this machine ends up in the export. Must run before agenttrace.server is imported."""
    global STATE_HOME
    if STATE_HOME is None:
        STATE_HOME = tempfile.mkdtemp(prefix="st-export-home-")
        os.environ["SWARM_TRACER_HOME"] = STATE_HOME
        os.environ["SWARM_TRACER_RULES"] = os.path.join(STATE_HOME, "rules.json")
    return STATE_HOME


def scrub(text):
    """Take this machine's folders out of a saved response: the state folder, the clone and the home folder."""
    pairs = []
    if STATE_HOME:
        pairs += [(os.path.realpath(STATE_HOME), "~/.swarm-tracer"), (STATE_HOME, "~/.swarm-tracer")]
    pairs += [(ROOT + os.sep, ""), (ROOT, "."), (os.path.expanduser("~"), "~")]
    for a, b in pairs:
        if a and a not in ("/", ""):
            text = text.replace(a, b)
    return text


def start_server(path, pack, name, port=0):
    """Load the dataset and serve it on 127.0.0.1 with POST refused. Returns (httpd, base url, session)."""
    isolate_state()
    from .. import server

    class ReadOnly(server.Handler):
        def log_message(self, fmt, *args):
            pass

        def do_POST(self):
            if not self.guard():
                return
            self.close_connection = True
            self.send_json({"error": STATIC_MESSAGE}, 403)

    server.run_load(path, pack, {}, name)
    ThreadingHTTPServer.request_queue_size = 128
    httpd = ThreadingHTTPServer(("127.0.0.1", port), ReadOnly)
    threading.Thread(target=httpd.serve_forever, daemon=True).start()
    return httpd, f"http://127.0.0.1:{httpd.server_address[1]}", server.STATE["session"]


def get(base, url, timeout=300):
    """(status, parsed JSON or None, raw bytes) of GET base+url."""
    code, data, _ = smoke.http(base, url, timeout=timeout)
    return code, (data if isinstance(data, (dict, list)) else None)


