def population(sess):
    """Every record id, actor, place and pair of the loaded session."""
    recs = [e.id for e in sess.events]
    actors = sorted(sess.by_actor)
    places = sorted(sess.channel_row)
    pairs = [(r["from"], r["to"]) for r in sess.pair_rows]
    return {"rec": recs, "actor": actors, "place": places, "pair": pairs}


def pick_samples(sess, pop):
    """A few of each for the crawl: records of each kind (one with messages), a token and a run, busy places."""
    recs, kinds = [], set()
    for e in sess.events:
        if e.kind not in kinds:
            kinds.add(e.kind)
            recs.append(e.id)
    recs += [r for r in list(sess.del_in)[:1] + list(sess.del_out)[:1] if r not in recs]
    named = [a for a in pop["actor"] if not a.startswith("run:")]
    runs = [a for a in pop["actor"] if a.startswith("run:")]
    actors = sorted(named, key=lambda a: -len(sess.by_actor[a]))[:1] + runs[:1]
    places = sorted(pop["place"], key=lambda c: -(sess.channel_row[c].get("deliveries") or 0))[:2]
    return {"rec": recs, "actor": actors, "place": places, "pair": pop["pair"][:1]}


def expand(seen, samples, pop):
    """Requests to make beyond the recorded ones: each recorded request that names a sample record, actor,
    place or pair, repeated for every record, actor, place and pair."""
    out, done = [], set()
    every = set(samples.get("rec") or ()) | set(samples.get("actor") or ()) | set(samples.get("place") or ())
    every |= {x for pair in samples.get("pair") or () for x in pair}

    def add(path, q):
        k = canon(path, q)
        if k not in done:
            done.add(k)
            out.append((path, q))

    for url in seen:
        path, q = parse(url)
        if path in LOCAL_PATHS or SERVER_ONLY.search(path):
            continue
        add(path, q)
    for url in seen:
        path, q = parse(url)
        if path in LOCAL_PATHS or SERVER_ONLY.search(path):
            continue
        for kind in ("rec", "actor", "place"):
            for name, v in q.items():
                if v in samples.get(kind, ()):
                    others = {k: x for k, x in q.items() if k != name}
                    if any(x in every for x in others.values()):
                        continue        # two ids in one request (a pair): handled below
                    for x in pop[kind]:
                        add(path, dict(others, **{name: x}))
        for a, b in samples.get("pair") or ():
            names = [(na, nb) for na, va in q.items() for nb, vb in q.items() if va == a and vb == b and na != nb]
            for na, nb in names:
                for x, y in pop["pair"]:
                    add(path, dict(q, **{na: x, nb: y}))
    return out


