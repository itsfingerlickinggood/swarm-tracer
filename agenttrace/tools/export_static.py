def open_view(br, tab, sub=None, quiet=0.6):
    if sub:      # FX_WANT: the Forensics tab otherwise keeps the section it showed last, whatever the address says
        br.eval(f"location.hash = {json.dumps('tab=forensics&fx=' + sub)}; FX_WANT = {json.dumps(sub)}; goTab('forensics')")
    else:
        br.eval(f"goTab({json.dumps(tab)})")
    return br.settle(quiet=quiet, busy_expr=smoke.BUSY_JS, timeout=120)


def view_names(br, tabs):
    out = []
    for tab in tabs:
        subs = [None]
        if tab == "forensics":
            subs = br.eval("(window.FX_SECTIONS || []).map((x) => x.id)") or [None]
        out += [(tab, sub) for sub in subs]
    return out


def crawl(base, samples, clicks=60, per_kind=8, log=print):
    """Visit everything in headless Chrome; returns the GET /api/... requests made, in order."""
    br = Recorder()
    try:
        br.navigate(base + "/")
        if not br.wait_until("typeof S !== 'undefined' && !!S.summary", timeout=120):
            raise RuntimeError("the app did not load the dataset")
        br.settle(busy_expr=smoke.BUSY_JS, timeout=90)
        tabs = br.eval("Object.keys(VIEWS)") or smoke.TABS
        tabs = [t for t in smoke.TABS if t in tabs] + [t for t in tabs if t not in smoke.TABS]
        views = view_names(br, tabs)
        for unit in ("agent", "token"):
            br.eval(f"setUnit({json.dumps(unit)})")
            for tab, sub in views:
                open_view(br, tab, sub)
                if unit != "agent" or not clicks:
                    continue
                todo = br.eval(CLICKABLE_JS % per_kind) or []      # up to per_kind controls that look alike (rows of a list)
                for i in todo[:clicks]:
                    try:
                        br.eval(CLICK_JS % i, timeout=15)
                        br.settle(quiet=0.25, timeout=20)
                        if br.eval("S.tab") != tab:
                            open_view(br, tab, sub, quiet=0.25)
                    except Exception as e:       # a control that navigates or throws must not stop the export
                        log(f"  click {tab}/{sub or ''} #{i}: {type(e).__name__}: {e}")
                        open_view(br, tab, sub, quiet=0.25)
            log(f"  visited {len(views)} views counting by {unit}: {len(br.seen)} requests so far")
        br.eval("setUnit('agent')")
        for fn, key in (("selectEvent", "rec"), ("inspectActor", "actor"), ("inspectPlace", "place")):
            for v in samples.get(key) or []:
                br.eval(f"{fn}({json.dumps(v)})")
                br.settle(busy_expr=smoke.TRACE_BUSY_JS, timeout=60)
                # the Inspector's own controls (sections that load when opened)
                for i in (br.eval(CLICKABLE_JS.replace("#left", "#trace") % 1) or [])[:12]:
                    try:
                        br.eval(CLICK_JS.replace("#left", "#trace") % i, timeout=15)
                        br.settle(quiet=0.25, timeout=20)
                    except Exception:
                        pass
        # the Start-here guide and the case file drawer read from the server too
        for b in ("guidebtn", "casebtn", "glossbtn"):
            br.eval(f"document.getElementById({json.dumps(b)})?.click()")
            br.settle(quiet=0.4, timeout=30)
        return list(br.seen)
    finally:
        br.close()


