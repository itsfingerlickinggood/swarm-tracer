class Recorder(smoke.Browser):
    """The smoke test's browser, also keeping every GET /api/... the page makes."""

    def __init__(self, *a, **kw):
        self.seen = []
        super().__init__(*a, **kw)
        # a control that opens a dialog (a prompt for a note, a confirm) would block the page for good
        self.call("Page.addScriptToEvaluateOnNewDocument", {"source":
                  "window.prompt = () => null; window.confirm = () => false; window.alert = () => {}; window.print = () => {};"})

    def _handle(self, msg):
        if msg.get("method") == "Network.requestWillBeSent":
            r = (msg.get("params") or {}).get("request") or {}
            u = urllib.parse.urlparse(r.get("url", ""))
            if r.get("method") == "GET" and u.path.startswith("/api/"):
                url = u.path + ("?" + u.query if u.query else "")
                if url not in self.seen:
                    self.seen.append(url)
        super()._handle(msg)


CLICKABLE_JS = r"""(() => {
  const all = [...document.querySelectorAll('#left button, #left select, #left summary, #left [role=tab], #left a[href^="#"], #left input[type=checkbox], #left input[type=radio]')];
  const seen = {}, out = [];
  all.forEach((el, i) => {
    if (el.disabled || el.offsetParent === null) return;
    const data = Object.keys(el.dataset).sort().join(',');
    const sig = el.tagName + '|' + el.className + '|' + data + '|' + (data ? '' : (el.textContent || '').trim().slice(0, 24));
    seen[sig] = (seen[sig] || 0) + 1;
    if (seen[sig] <= %d) out.push(i);
  });
  return out; })()"""
