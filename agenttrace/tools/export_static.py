def tool_version():
    """The Swarm Tracer version: pyproject.toml in a clone, else the installed package's."""
    try:
        with open(os.path.join(ROOT, "pyproject.toml"), encoding="utf-8") as f:
            m = re.search(r'^version\s*=\s*"([^"]+)"', f.read(), re.M)
        if m:
            return m.group(1)
    except OSError:
        pass
    try:
        from importlib.metadata import version
        return version("swarm-tracer")
    except Exception:
        return "unknown"


def export(dataset, out, clicks=60, browser=True, max_records=None, log=print):
    spec = DATASETS.get(dataset)
    if not spec:
        raise SystemExit(f"unknown dataset {dataset!r}. Only datasets whose terms allow publishing are listed "
                         f"in agenttrace/tools/export_static.py DATASETS: {', '.join(sorted(DATASETS))}")
    version = tool_version()
    t0 = time.time()
    log(f"loading {spec['path']} ...")
    httpd, base, sess = start_server(spec["path"], spec["pack"], spec["name"])
    try:
        pop = population(sess)
        if max_records:
            pop["rec"] = pop["rec"][:max_records]
        samples = pick_samples(sess, pop)
        seen = []
        if browser:
            log("crawling the app in headless Chrome ...")
            seen = crawl(base, samples, clicks=clicks, log=log)
        seen += [u for u in baseline_requests(samples) if u not in seen]
        todo = expand(seen, samples, pop)
        log(f"{len(seen)} requests recorded; fetching {len(todo)} responses ...")
        responses, errors, lite_same = {}, [], 0
        for path, q in todo:
            code, data = get(base, request_url(path, q))
            if data is None or code >= 500:
                errors.append(f"{code} {canon(path, q)}")
                continue
            if code >= 400:
                data = {"$error": data.get("error") or f"HTTP {code}"} if isinstance(data, dict) else {"$error": f"HTTP {code}"}
            responses[(path, canon(path, q))] = data
        # a record's short form is saved only where it differs from the full one (static.js falls back)
        for (path, key) in list(responses):
            if path == "/api/event" and "lite=" in key:
                p, q = parse(key)
                q.pop("lite", None)
                if responses.get((path, canon(path, q))) == responses[(path, key)]:
                    del responses[(path, key)]
                    lite_same += 1
        if errors:
            log(f"{len(errors)} requests failed and were left out: " + "; ".join(errors[:8]))
        meta = {"static": True, "dataset": dataset, "title": spec["title"], "licence": spec["licence"],
                "name": spec["name"], "records": len(sess.events), "version": version,
                "drilldown": {"records": len(pop["rec"]), "actors": len(pop["actor"]), "places": len(pop["place"]), "pairs": len(pop["pair"])},
                "message": STATIC_MESSAGE}
        stats = write_export(out, responses, build_index(sess), meta, log)
        stats.update(requests=len(responses), failed=errors, seconds=round(time.time() - t0, 1), lite_merged=lite_same)
        log(f"wrote {out}: {stats['files']} files, {stats['bytes'] / 1e6:.2f} MB, {len(responses)} saved responses "
            f"in {stats['seconds']} s")
        return stats
    finally:
        httpd.shutdown()
        httpd.server_close()


def baseline_requests(samples):
    """Requests the app is known to make, so an export without Chrome (--no-browser) still opens."""
    out = ["/api/packs", "/api/state", "/api/x/units_map", "/api/x/units_summary?unit=agent", "/api/lanes", "/api/messages",
           "/api/places_map", "/api/sim", "/api/context", "/api/spread", "/api/gaps", "/api/x/case", "/api/x/live_status"]
    for r in samples.get("rec") or ():
        out += ["/api/event?id=" + urllib.parse.quote(r), "/api/event?lite=1&id=" + urllib.parse.quote(r)]
    out += ["/api/actor?a=" + urllib.parse.quote(a) for a in samples.get("actor") or ()]
    out += ["/api/place?ch=" + urllib.parse.quote(c) for c in samples.get("place") or ()]
    out += [f"/api/conversation?a={urllib.parse.quote(a)}&b={urllib.parse.quote(b)}" for a, b in samples.get("pair") or ()]
    return out


