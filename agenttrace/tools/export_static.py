"""Export the app as static files: the hosted demo (docs/demo/ on GitHub Pages).

    python3 -m agenttrace.tools.export_static --out docs/demo [--dataset demo] [--clicks 60] [--no-browser]
    python3 -m agenttrace.tools.export_static --verify http://localhost:8034/demo/ [--dataset demo]
    python3 -m agenttrace.tools.export_static --verify-dir docs/demo [--port 8034]
    python3 -m agenttrace.tools.export_static --serve docs --port 8034

What it does:
1. loads the dataset into a server in this process (POST refused, so nothing a page does can change it);
2. opens the app in headless Chrome (the smoke test's DevTools plumbing), visits every tab and every
   Forensics section in both counting units, opens one record, actor, place and conversation in the
   Inspector, clicks a bounded number of controls in each view, and records every GET /api/... the app makes;
3. repeats each drill-down request (any recorded request that names the sample record, actor, place or
   pair) for every record, actor, place and pair of the dataset;
4. saves every response under OUT/data/ in pack files, writes an index of all records for the queries the
   static page answers itself (Events filters, pair and list filters, the search box), copies the app, and
   switches the copy to static mode (a <meta name="st-static"> tag and static.js, see static_shim.js).

A request maps to a file with no server: the key is the path plus its non-empty query parameters sorted by
name ("/api/event?id=R1"); the file is data/<path slug>-<FNV-1a(key) mod N>.json, where N (the number of
pack files of that path) is in static.json; the file holds {key: response}. core.js's api() does the same
arithmetic in static mode. Everything in the page is fetched with relative URLs, so the export works under
any folder (/swarm-tracer/demo/).

Only the datasets in DATASETS may be exported: each is listed with the terms that allow publishing it. The
simulated demo swarm ships with the package. Add a dataset here once its licence is confirmed.

--verify opens a served export in headless Chrome and checks every tab (no console error, no failed
request, no blank view), the Inspector, the "not available" states, and that the queries the page answers
itself give the server's answers.
"""
