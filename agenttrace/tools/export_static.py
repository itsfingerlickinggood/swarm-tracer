def parse(url):
    """(path, {param: value}) of a request: first value of each parameter, empty values dropped."""
    u = urllib.parse.urlparse(url)
    q = {}
    for k, v in urllib.parse.parse_qsl(u.query, keep_blank_values=False):
        q.setdefault(k, v)
    return u.path, q


def canon(path, q):
    return path + "?" + "&".join(f"{k}={q[k]}" for k in sorted(q))


def fnv(s):
    h = 0x811C9DC5
    for b in s.encode("utf-8"):
        h = ((h ^ b) * 0x01000193) & 0xFFFFFFFF
    return h


def slug(path):
    return re.sub(r"[^A-Za-z0-9]+", "_", re.sub(r"^/api/", "", path))


def request_url(path, q):
    return path + ("?" + urllib.parse.urlencode(q) if q else "")


