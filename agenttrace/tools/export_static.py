def build_index(sess):
    """Everything static.js needs to answer /api/events, /api/x/units_events, /api/pairs, /api/list and
    /api/search the way the server does (Session.search, units._events_get, Session.pairs, Session.listing,
    insight.omni)."""
    from .. import units
    rows = [sess.event_row(e) for e in sess.events]
    find = ["\x00".join([e.id.lower(), e.text.lower(), (e.actor or "").lower(), (e.channel or "").lower()]) for e in sess.events]
    lists = {k: v for k, v in sess._lists().items()}
    try:
        amap = dict(units.agents(sess)[1])
    except Exception:
        amap = {}
    return {
        "events": rows, "find": find,
        "pairs": [{k: v for k, v in r.items() if not k.startswith("_")} for r in sess.pair_rows],
        "pair_keys": [r["_key"] for r in sess.pair_rows],
        "lists": lists,
        "list_find": {k: [json.dumps(r, default=str).lower() for r in v] for k, v in lists.items()},
        "actors": [{"actor": a, "records": len(ids), "kind": sess.actor[ids[0]][1]}
                   for a, ids in sess.by_actor.items() if not a.startswith("run:")],
        "places": [{"channel": ch, "messages": row["deliveries"], "ops": row["writes"] + row["reads"]}
                   for ch, row in sess.channel_row.items()],
        "agent_of": amap,
    }


# ---------------------------------------------------------------------- writing

def dumps(obj):
    return json.dumps(obj, ensure_ascii=False, default=str, separators=(",", ":"), sort_keys=False)


# Saved responses repeat themselves: a record's row (id, kind, time, actor, preview ...) sits inside every
# response that lists it, and the same actor or program summary inside every record of that actor or program.
# Two substitutions take the repeats out (static_shim.js decode() puts them back):
#   {"$r": id, ...}   an object that holds every field of record id's row with the row's values, plus the rest;
#                     the row is in data/records-index.json ("events")
#   {"$s": n}         a value that occurs more than once among one path's responses; it is item n of
#                     data/<path slug>-shared.json
SHARE_MIN = 48               # characters of JSON a repeated value needs before it is worth a reference
SHARE_FILE_MIN = 20_000      # a path gets a shared file only if it saves this many bytes


def norm(obj):
    """The response as the browser will read it: through JSON, this machine's folders taken out."""
    return json.loads(scrub(dumps(obj)))


def ref_rows(node, rows):
    """Swap every object that carries a whole record row for {"$r": id, the other fields}."""
    if isinstance(node, list):
        return [ref_rows(x, rows) for x in node]
    if not isinstance(node, dict):
        return node
    if "$r" in node or "$s" in node:
        raise SystemExit("a response uses the key $r or $s, which the export reserves")
    row = rows.get(node.get("id")) if isinstance(node.get("id"), str) else None
    if row is not None and all(k in node and node[k] == v for k, v in row.items()):
        out = {"$r": node["id"]}
        out.update((k, ref_rows(v, rows)) for k, v in node.items() if k not in row)
        return out
    return {k: ref_rows(v, rows) for k, v in node.items()}


def share(items):
    """items: {key: object}. Returns ({key: object with {"$s": n} for repeated values}, [shared values]) or
    (items, None) when sharing would save too little to be worth another file."""
    count, size = {}, {}

    def scan(node):
        if isinstance(node, (dict, list)):
            for x in (node.values() if isinstance(node, dict) else node):
                scan(x)
        elif not isinstance(node, str):
            return
        d = dumps(node)
        if len(d) >= SHARE_MIN:
            count[d] = count.get(d, 0) + 1

    for v in items.values():
        scan(v)
    table, where, saved = [], {}, [0]

    def enc(node, top=False):
        if isinstance(node, (dict, list, str)) and not top:
            d = dumps(node)
            if count.get(d, 0) > 1:
                if d not in where:
                    where[d] = len(table)
                    table.append(None)
                    table[where[d]] = enc(node, top=True)       # its own repeats are shared too
                else:
                    saved[0] += len(d) - 10
                return {"$s": where[d]}
        if isinstance(node, dict):
            return {k: enc(v) for k, v in node.items()}
        if isinstance(node, list):
            return [enc(x) for x in node]
        return node

    out = {k: enc(v, top=True) for k, v in items.items()}
    if saved[0] < SHARE_FILE_MIN:
        return items, None
    return out, table


def decode(node, rows, shared):
    """What static_shim.js decode() does: the response a saved object stands for."""
    if isinstance(node, list):
        return [decode(x, rows, shared) for x in node]
    if not isinstance(node, dict):
        return node
    if "$s" in node:
        return decode(shared[node["$s"]], rows, shared)
    out = dict(rows[node["$r"]]) if "$r" in node else {}
    out.update((k, decode(v, rows, shared)) for k, v in node.items() if k != "$r")
    return out


def read_saved(out, url):
    """The response an export folder holds for a request (None if it was not saved), decoded."""
    with open(os.path.join(out, "static.json"), encoding="utf-8") as f:
        man = json.load(f)
    path, q = parse(url)
    key, n = canon(path, q), man["paths"].get(path)
    if not n:
        return None

    def load(name):
        with open(os.path.join(out, "data", name), encoding="utf-8") as f:
            return json.load(f)

    pack = load(f"{slug(path)}-{fnv(key) % n}.json")
    if key not in pack:
        return None
    rows = {r["id"]: r for r in load("records-index.json")["events"]} if path in man.get("refs", ()) else {}
    shared = load(f"{slug(path)}-shared.json") if path in man.get("shared", ()) else []
    return decode(pack[key], rows, shared)


def write_export(out, responses, index, meta, log=print):
    """responses: {(path, canonical key): object}. Writes data/, static.json and the app. Returns stats."""
    if os.path.isdir(out) and os.listdir(out) and not os.path.isfile(os.path.join(out, "static.json")):
        raise SystemExit(f"{out} exists and is not an export (no static.json in it): not overwriting it")
    shutil.rmtree(out, ignore_errors=True)
    os.makedirs(os.path.join(out, "data"))
    for root, dirs, files in os.walk(APP_DIR):
        dirs[:] = [d for d in dirs if not d.startswith(".")]
        for f in files:
            if f.startswith(".") or not f.endswith((".js", ".css", ".html", ".svg", ".png", ".ico", ".woff2")):
                continue
            dst = os.path.join(out, os.path.relpath(os.path.join(root, f), APP_DIR))
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copyfile(os.path.join(root, f), dst)
    shutil.copyfile(SHIM, os.path.join(out, "static.js"))
    with open(os.path.join(out, "static.css"), "w", encoding="utf-8") as f:
        f.write(STATIC_CSS)
    with open(os.path.join(out, "index.html"), encoding="utf-8") as f:
        html = f.read()
    html = static_index(html, meta["dataset"])
    with open(os.path.join(out, "index.html"), "w", encoding="utf-8") as f:
        f.write(html)

    by_path = {}
    for (path, key), obj in responses.items():
        by_path.setdefault(path, {})[key] = obj
    index = norm(index)
    rows = {r["id"]: r for r in index["events"]}
    paths, slugs, refs, shared_paths = {}, {}, [], []
    for path in sorted(by_path):
        sl = slug(path)
        if slugs.setdefault(sl, path) != path:
            raise SystemExit(f"two API paths share the file name {sl}: {slugs[sl]} and {path}")
        objs = {k: ref_rows(norm(v), rows) for k, v in by_path[path].items()}
        if any('"$r":' in dumps(v) for v in objs.values()):
            refs.append(path)
        objs, table = share(objs)
        if table is not None:
            shared_paths.append(path)
            with open(os.path.join(out, "data", f"{sl}-shared.json"), "w", encoding="utf-8") as f:
                f.write("[" + ",\n".join(dumps(x) for x in table) + "]\n")
        items = {k: dumps(v) for k, v in objs.items()}
        n = max(1, round(sum(len(v) for v in items.values()) / PACK_BYTES))
        packs = [[] for _ in range(n)]
        for k in sorted(items):
            packs[fnv(k) % n].append(dumps(k) + ":" + items[k])
        for i, p in enumerate(packs):
            with open(os.path.join(out, "data", f"{sl}-{i}.json"), "w", encoding="utf-8") as f:
                f.write("{" + ",\n".join(p) + "}\n")
        paths[path] = n
    with open(os.path.join(out, "data", "records-index.json"), "w", encoding="utf-8") as f:
        f.write(dumps(index) + "\n")
    man = dict(meta, paths=paths, refs=refs, shared=shared_paths, local=list(LOCAL_PATHS), requests=len(responses))
    with open(os.path.join(out, "static.json"), "w", encoding="utf-8") as f:
        json.dump(man, f, ensure_ascii=False, indent=1)
        f.write("\n")
    return dir_stats(out)


def static_index(html, dataset):
    """index.html switched to static mode: the flag, the static stylesheet and static.js ahead of core.js."""
    if 'name="st-static"' in html:
        return html
    html = html.replace('<title>Swarm Tracer</title>',
                        f'<title>Swarm Tracer demo</title>\n<meta name="st-static" content="{dataset}">\n'
                        '<meta name="robots" content="noindex">\n<link rel="icon" href="data:,">', 1)
    html = html.replace('</head>', '<link rel="stylesheet" href="static.css">\n</head>', 1)
    html = html.replace('<script src="core.js"></script>', '<script src="static.js"></script>\n<script src="core.js"></script>', 1)
    if 'src="static.js"' not in html or 'name="st-static"' not in html:
        raise SystemExit("agenttrace/app/index.html changed shape: could not switch the copy to static mode")
    return html


def dir_stats(d):
    n = size = 0
    for root, _, files in os.walk(d):
        for f in files:
            n += 1
            size += os.path.getsize(os.path.join(root, f))
    return {"files": n, "bytes": size}


