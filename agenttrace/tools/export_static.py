def verify(url, dataset="demo", log=print, shots=None):
    """Open a served export and check it. Returns a list of problems (empty when it passes)."""
    url = url.rstrip("/")
    problems, res = [], smoke.Result("static")
    spec = DATASETS[dataset]
    httpd, base, sess = start_server(spec["path"], spec["pack"], spec["name"])
    br = smoke.Browser()
    try:
        pop = population(sess)
        s = pick_samples(sess, pop)
        ids = {"rec": pop["rec"][len(pop["rec"]) // 2], "actor": s["actor"][0] if s["actor"] else None,
               "place": pop["place"][-1] if pop["place"] else None}
        smoke.browser_cells(res, br, url, ids, smoke.TABS, forensics_sections=False)
        if not br.eval("typeof goTab === 'function' && typeof S !== 'undefined' && !!S.summary"):
            return [f"{c['area']} {c['name']}: {c['error']}" for c in res.failed] or ["the page did not load"]
        # every tab and every Forensics section: it settles, shows something, logs no error, fails no request,
        # and opens on nothing the export did not save
        for tab, sub in view_names(br, smoke.TABS):
            name = tab + (f"/{sub}" if sub else "")
            br.mark()
            settled = open_view(br, tab, sub)
            info = br.eval(r"""(() => { const el = document.querySelector('#left'), on = document.querySelector('.fxnav button.on');
              return { len: el.innerText.trim().length, text: el.innerText, section: on ? on.dataset.fx : null,
                       warns: [...el.querySelectorAll('.warn')].map((w) => w.innerText.trim().slice(0, 200)) }; })()""")
            bad = []
            if not settled:
                bad.append("did not settle")
            if br.events:
                bad.append(smoke._events_text(br.events))
            if sub and info["section"] != sub:
                bad.append(f"shows section {info['section']!r}")
            if info["len"] < 30:
                bad.append("almost blank")
            if "hosted demo" in info["text"]:
                bad.append("opens on a request that was not saved")
            bad += ["warn box: " + w for w in info["warns"] if smoke.ERRORISH.search(w)]
            res.add("view", name, not bad, "; ".join(bad))
        for c in res.cells:
            log(f"  {'ok  ' if c['ok'] else 'FAIL'} {c['area']:9} {c['name'][:40]:40} {c['error'][:200]}")
        problems += [f"{c['area']} {c['name']}: {c['error']}" for c in res.failed]
        # the page's own queries give the server's answers
        probes = list(LOCAL_PROBES)
        named = [a for a in pop["actor"] if not a.startswith("run:")]
        for a in named[:3]:
            probes += [f"/api/events?actor={urllib.parse.quote(a)}&limit=40", f"/api/x/units_events?actor={urllib.parse.quote(a)}&limit=40",
                       f"/api/search?q={urllib.parse.quote(a)}"]
        for it in list((sess.summary().get("intents") or {}))[:3]:
            probes.append(f"/api/events?intent={urllib.parse.quote(it)}&limit=25")
        for tg in list((sess.summary().get("evidence_tags") or {}))[:2]:
            probes += [f"/api/events?tag={urllib.parse.quote(tg)}&limit=25", f"/api/x/units_events?tag={urllib.parse.quote(tg)}&limit=25"]
        same = 0
        for p in probes:
            code, want = get(base, p)
            got = br.eval(f"ST_STATIC.api({json.dumps(p)}).then((r) => JSON.stringify(r)).catch((e) => JSON.stringify({{$threw: e.message}}))",
                          await_promise=True)
            got = json.loads(got)
            if code >= 400:
                ok = "$threw" in got
            else:
                ok = json.loads(scrub(json.dumps(want, default=str, ensure_ascii=False))) == got
            same += ok
            if not ok:
                problems.append(f"the static page answers {p} differently from the server")
        log(f"  {same}/{len(probes)} in-page queries match the server")
        # drill-down: a record, actor and place the crawl never opened
        for p in ([f"/api/event?id={urllib.parse.quote(r)}" for r in pop["rec"][::max(1, len(pop["rec"]) // 7)]]
                  + [f"/api/event?lite=1&id={urllib.parse.quote(pop['rec'][-1])}"]
                  + [f"/api/actor?a={urllib.parse.quote(a)}" for a in pop["actor"][::max(1, len(pop["actor"]) // 5)]]
                  + [f"/api/place?ch={urllib.parse.quote(c)}" for c in pop["place"]]):
            code, want = get(base, p)
            got = json.loads(br.eval(f"ST_STATIC.api({json.dumps(p)}).then((r) => JSON.stringify(r)).catch((e) => JSON.stringify({{$threw: e.message}}))", await_promise=True))
            if json.loads(scrub(json.dumps(want, default=str, ensure_ascii=False))) != got:
                problems.append(f"saved response differs from the server: {p}")
        # the states that replace what needs a server
        br.mark()
        said = br.eval("api('/api/x/case', {method: 'POST', body: '{}'}).then(() => 'answered', (e) => e.message)", await_promise=True)
        if said != STATIC_MESSAGE:
            problems.append(f"a POST in static mode said {said!r}")
        for btn, word in (("loadbtn", "hosted demo"), ("livebtn", "hosted demo")):
            br.eval(f"document.getElementById('{btn}').click()")
            txt = br.eval("(document.getElementById('stnotice') || {}).hidden === false ? document.getElementById('stnotice').innerText : ''") or ""
            if word not in txt:
                problems.append(f"#{btn} did not show the not-available note (shows {txt[:80]!r})")
            br.eval("document.querySelector('[data-stclose]')?.click()")
        ai = br.eval("(document.querySelector('.stai') || {}).innerText || ''")
        if "Not available in the hosted demo" not in ai:
            problems.append("the AI pane does not say it is unavailable")
        if br.eval("getComputedStyle(document.getElementById('ask')).display") != "none":
            problems.append("the AI question box is still shown")
        missing = br.eval("api('/api/x/nothing_like_this').then(() => 'answered', (e) => e.message)", await_promise=True)
        if "not saved in the hosted demo" not in str(missing):
            problems.append(f"an unsaved request said {missing!r}")
        br.settle(quiet=0.4, timeout=20)
        if br.events:
            problems.append("errors while checking the unavailable states: " + smoke._events_text(br.events))
        outside = br.eval(f"performance.getEntriesByType('resource').map((r) => r.name).filter((n) => !n.startsWith({json.dumps(url + '/')}))")
        if outside:
            problems.append("requests outside the export folder: " + ", ".join(outside[:5]))
    finally:
        br.close()
        httpd.shutdown()
        httpd.server_close()
    return problems


def serve_folder(folder, port=0):
    """Serve a folder on 127.0.0.1 the way a static host does (a queue long enough for a page's burst of requests)."""
    import functools
    from http.server import SimpleHTTPRequestHandler

    class Quiet(SimpleHTTPRequestHandler):
        def log_message(self, fmt, *args):
            pass

    ThreadingHTTPServer.request_queue_size = 128
    httpd = ThreadingHTTPServer(("127.0.0.1", port), functools.partial(Quiet, directory=folder))
    threading.Thread(target=httpd.serve_forever, daemon=True).start()
    return httpd, f"http://127.0.0.1:{httpd.server_address[1]}"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", help="folder to write (e.g. docs/demo); replaced if it is an earlier export")
    ap.add_argument("--dataset", default="demo", help="which dataset to publish: " + ", ".join(sorted(DATASETS)))
    ap.add_argument("--clicks", type=int, default=60, help="controls to try in each view while recording requests (0: none)")
    ap.add_argument("--no-browser", action="store_true", help="skip headless Chrome: save only the known requests and the drill-downs")
    ap.add_argument("--max-records", type=int, help="save the Inspector's drill-down for the first N records only (default: all)")
    ap.add_argument("--verify", metavar="URL", help="check a served export instead (e.g. http://localhost:8034/demo/)")
    ap.add_argument("--verify-dir", metavar="FOLDER", help="the same check on an export folder: serves its parent folder itself "
                    "(so the page sits under /NAME/ as on GitHub Pages) on --port")
    ap.add_argument("--port", type=int, default=0, help="port for --verify-dir and --serve (default: any free port)")
    ap.add_argument("--serve", metavar="FOLDER", help="only serve a folder on 127.0.0.1 --port until interrupted (e.g. docs, "
                    "to look at docs/demo under /demo/)")
    ap.add_argument("--json", help="write the result as JSON here")
    a = ap.parse_args(argv)
    if a.serve:
        web, base = serve_folder(os.path.abspath(a.serve), a.port)
        print(f"serving {a.serve} at {base}/ (Ctrl-C to stop)", flush=True)
        try:
            threading.Event().wait()
        except KeyboardInterrupt:
            pass
        return 0
    if a.verify_dir:
        d = os.path.abspath(a.verify_dir)
        web, base = serve_folder(os.path.dirname(d), a.port)
        try:
            a.verify = f"{base}/{os.path.basename(d)}/"
            problems = verify(a.verify, a.dataset)
        finally:
            web.shutdown()
            web.server_close()
        for p in problems:
            print("FAIL " + p)
        print(f"static export at {a.verify}: " + ("ok" if not problems else f"{len(problems)} problems"))
        result = {"problems": problems}
    elif a.verify:
        problems = verify(a.verify, a.dataset)
        for p in problems:
            print("FAIL " + p)
        print("static export: " + ("ok" if not problems else f"{len(problems)} problems"))
        result = {"problems": problems}
    elif a.out:
        result = export(a.dataset, a.out, clicks=a.clicks, browser=not a.no_browser, max_records=a.max_records)
        problems = result["failed"]
    else:
        ap.error("give --out FOLDER to export or --verify URL to check a served export")
    if a.json:
        with open(a.json, "w", encoding="utf-8") as f:
            json.dump(result, f, indent=1)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
